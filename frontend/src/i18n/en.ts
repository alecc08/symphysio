/* The English side of the dictionary — and the type every other language is checked against.

   One flat key space, dotted by screen. `fr.ts` is typed `Record<MessageKey, string>`,
   so `npm run build` fails when a French string is missing. That is why the copy
   lives in one object per language instead of scattered next to the components:
   "fully translated" stops being a claim and becomes something the compiler
   refuses to let you break.

   Interpolation is `{name}` and nothing else — no plurals engine, no JSX inside
   strings. Where French needs different word order rather than a swapped word,
   there are two keys, not a rule.
*/

